/** L1 图语义段（稳定前缀；节点种类 / 连线语义 / 协作组与虚拟节点判据）。 */
export const ORG_SOP_L1_GRAPH_SEMANTICS = `组织规划图语义（L1：图模型与硬规则）：

一、节点种类（9 种，kind 字段为判据）
1. start：启动节点，模式一入口；全图仅 1 个，只允许流程出线；
2. end：结束节点，模式一出口；全图仅 1 个，只允许流程入线；
3. pause：暂停节点，运行到此落检查点并等待恢复；必须同时有流程入线与流程出线；
4. agent：子代理执行节点，承担可独立交付的任务；
5. parent：父代理节点，既是调度中枢也是执行单元；被流程线连接时父代理亲自执行该节点任务，通常执行规划型任务；
6. group：协作组节点，组内成员并行开工，组员之间用 wf_ask_agent 互相发消息；
7. proxy：虚拟节点（主节点别名引用），无独立配置，只能引用角色节点（agent/parent）；
8. file：受管文件数据源节点，必须配置实际文件；
9. database：数据库数据源节点，必须配置路径或连接。

二、连线语义
1. flow（流程线）：执行顺序与父子调度关系；可挂 condition 条件分支（{type:'pass'} / {type:'fail'}，text 型判断用 {type:'content', label}）；
2. ctx（上下文线）：把上游最终产出注入下游节点；来源只能是角色节点、虚拟节点或受管文件节点；
3. db（数据库线）：数据库节点之间连线；目标必须是数据库节点。

三、协作组与虚拟节点的选择判据
- 需要多个角色**互相通信、交叉验证**（如多视角评审）→ 用 group：组卡片串在流程上，组员并行开工，成员之间可互发消息；组员之间不连 ctx 线。
- 需要**复用同一个角色实例与它已有的上下文**（同一角色在流程里再次出场）→ 用 proxy 指向该角色节点：不新增子代理、不重复消耗上下文，成本最低。
- 指向父代理的 proxy 且 data.role='milestone' = 父代理亲自复核的里程碑闸门，该轮**不会自动完成**，只能由父代理用 wf_graph_patch 的 mark_node 显式标记；闸门必须有流程入口，否则不会被驱动。

四、条件分支与数据节点的硬规则
- 同一源节点同一流程出上的条件线必须**成对**：有「通过」（type:'pass'）就必须有「不通过」（type:'fail'）。
- 流程必须保持无环 DAG：返工不得回指上游节点，要改成「前向 fail 分支 → 修复节点（可使用 proxy） → 在下游重新汇合」。
- 数据节点必须配置完整：file 节点要有实际文件或文本内容，database 节点要有本地路径或连接信息。
`

/**
 * 设计方法段（稳定前缀；取代原 L2 模式库）。
 *
 * 为什么删掉原来的「六种模式菜单」（用户裁决 A1）：pipeline / fan-out / review / data-injection
 * 都是模型从训练数据就能推断的通用结构，写在提示词里既占预算又无用；真正猜不出的是本插件的
 * 自定义语义（group/proxy/三通道连线/检查器规则），那部分已并入 L1。
 * 保留下来的是「交付物 → 落盘路径与消费方 → 并行判定」这条设计链路，以及两条只在本插件成立的
 * 成本约束（节点配置不可省、子代理按增量招募）。
 */
export const ORG_SOP_DESIGN_METHOD = `设计方法（按顺序想清楚三件事，再动手写补丁）：

第一步：列交付物清单。每组交付物对应一个可执行节点；一个节点只承担一件可独立验收的交付任务。
  合并判据：两件事无法分别验收、或拆开后下游拿不到额外信息，就合并成一个节点。

第二步：为每份交付物写明落盘路径与消费方。
  大产物（成稿、报告、文件等）一律要求节点写入工作区文件；节点交接只传「结论 + 产出文件路径 + 关键决策 + 未决问题」。
  凡有下游要读的产出，必须与下游建立 ctx 连线，否则下游无法完成交接。
  交付物没有任何下游消费方时（终端产出），不要加 ctx 线，也不要给评审节点。

第三步：判定并行与规模。
  只有「不同时修改同一批文件、且互不依赖」的任务才并行；否则串行。
  并行要有独立价值：拆成两个子代理的总成本 = 两次子代理开销 + 一次上下文交接，收益不明显就合并。

节点配置：每个 agent 节点至少要有 label、systemPrompt（该子代理角色定义、任务说明、执行规范）、presetId（工具组合，来自 wf_org_catalog 的 combos）。
  presetId 为空 = 这个节点运行时没有任何工具，是无效节点；provider/model 从 wf_org_catalog 的 models 里选。
`
